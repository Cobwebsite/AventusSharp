using System.Diagnostics;
using System.Security;
using CSharpExport.Container;

namespace CSharpExport;

internal sealed class FileToWrite(ProjectConfig config)
{
    private readonly Dictionary<string, List<BaseContainer>> files = new();

    public void RegisterType(BaseContainer container)
    {
        var relative = Path.GetRelativePath(Path.GetDirectoryName(config.CsProj)!, container.SourceFile);
        var name = Path.ChangeExtension(relative, ".g.cs");
        if (!files.TryGetValue(name, out var types))
            files[name] = types = new();
        types.Add(container);
    }

    public async Task<int> WriteAll()
    {
        Directory.CreateDirectory(config.OutputPath);
        foreach (var (name, types) in files)
            FileWriter.Write(Path.Combine(config.OutputPath, name),
                "// <auto-generated/>\n#nullable enable\n" +
                string.Join("\n", types.SelectMany(t => t.Usings.Split('\n', StringSplitOptions.RemoveEmptyEntries)).Distinct()) + "\n" +
                string.Join(Environment.NewLine, types.Select(t => t.Write())));
        var projectFile = Path.Combine(config.OutputPath, config.AssemblyName + ".csproj");
        var packages = string.Join(Environment.NewLine, config.Packages.Select(p =>
            $"    <PackageReference Include=\"{SecurityElement.Escape(p.Id)}\" Version=\"{SecurityElement.Escape(p.Version)}\" />"));
        FileWriter.Write(projectFile, $"""
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <Nullable>enable</Nullable>
                <ImplicitUsings>enable</ImplicitUsings>
                <AssemblyName>{SecurityElement.Escape(config.AssemblyName)}</AssemblyName>
              </PropertyGroup>
              <ItemGroup>
            {packages}
              </ItemGroup>
            </Project>
            """);
        Console.WriteLine($"{files.Count} fichier(s) exporté(s) vers {projectFile}");
        using var build = Process.Start(new ProcessStartInfo("dotnet")
        {
            ArgumentList = { "build", projectFile, "-v", "q" },
            UseShellExecute = false
        }) ?? throw new InvalidOperationException("Impossible de lancer dotnet build.");
        await build.WaitForExitAsync();
        if (build.ExitCode == 0)
            Console.WriteLine($"DLL : {Path.Combine(config.OutputPath, "bin", "Debug", "net10.0", config.AssemblyName + ".dll")}");
        return build.ExitCode;
    }
}
